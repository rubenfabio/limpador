//! `node_modules` of each project (T-04.01): one item per project, grouping the root's
//! and every monorepo package's folder.

use super::in_use_signal;
use super::javascript::{NPM_WITHOUT_LOCK, locked_manager};
use crate::collector::{
    AnalysisContext, CleanOutcome, Collector, CollectorDescriptor, CollectorError, Detection,
    KindSpec, Revalidation,
};
use crate::item::{Category, Item, ItemDraft, Nature, Resource, Risk};
use crate::message::Message;
use crate::ports::Platform;
use crate::projects::{Project, ends_with_folder, find_folders, project_at};
use crate::risk::Destination;
use crate::tree::{measure, remove};
use std::path::{Path, PathBuf};
use std::sync::Arc;

pub const ID: &str = "node-modules";
const KIND: &str = "node_modules";
const FOLDER: &str = "node_modules";
/// Monorepo packages rarely sit deeper than this below the project.
const MAX_DEPTH: u32 = 8;

pub struct NodeModulesCollector {
    platform: Arc<dyn Platform>,
}

impl NodeModulesCollector {
    pub fn new(platform: Arc<dyn Platform>) -> Self {
        Self { platform }
    }

    /// The item of `project`, or `None` when it has no `node_modules`.
    fn item(&self, project: &Project, others: &[&Path], ctx: &AnalysisContext) -> Option<Item> {
        let folders = find_modules(&project.root, others);
        if folders.is_empty() {
            return None;
        }
        let size = measure(&folders, self.platform.as_ref(), &ctx.stop);
        let lock = locked_manager(&project.root);
        let command = lock.unwrap_or(NPM_WITHOUT_LOCK).install;
        let main = project.root.join(FOLDER);
        let resource = if folders.contains(&main) {
            main
        } else {
            folders[0].clone()
        };

        let mut draft = ItemDraft::new(
            ID,
            KIND,
            Category::DependenciesAndBuilds,
            Resource::Path(resource),
            format!("{} · node_modules", project.name),
            Nature::Recreatable,
            Risk::Moderate,
        )
        .sizes(size.apparent, size.freeable)
        .reason(Message::new("reason.node_modules").with("count", folders.len()))
        .recreate(Message::new("recreate.run_command").with("command", command))
        .project_hint(&project.root);
        if lock.is_none() {
            draft = draft.alert(Message::new("alert.versions_may_differ"));
        }
        for folder in folders {
            draft = draft.part(folder);
        }
        draft.build().ok()
    }

    /// Projects found by the analysis, worktrees included (each has its own folders).
    fn projects(ctx: &AnalysisContext) -> Vec<&Project> {
        ctx.discovery
            .projects
            .iter()
            .chain(&ctx.discovery.worktrees)
            .collect()
    }
}

/// Every `node_modules` inside `root`, without entering another project (`others`),
/// another `node_modules`, a link or a junction.
fn find_modules(root: &Path, others: &[&Path]) -> Vec<PathBuf> {
    find_folders(root, others, MAX_DEPTH, &|relative| {
        ends_with_folder(relative, FOLDER)
    })
}

impl Collector for NodeModulesCollector {
    fn descriptor(&self) -> CollectorDescriptor {
        CollectorDescriptor {
            id: ID,
            kinds: vec![KindSpec {
                kind: KIND,
                category: Category::DependenciesAndBuilds,
                nature: Nature::Recreatable,
                restorable: false,
            }],
            catalog_locations: vec![],
        }
    }

    fn detect(&self, _ctx: &AnalysisContext) -> Detection {
        // Folders are read directly: nothing to install.
        Detection::Available
    }

    fn analyze(
        &self,
        ctx: &AnalysisContext,
        emit: &mut dyn FnMut(Item),
    ) -> Result<(), CollectorError> {
        let projects = Self::projects(ctx);
        let roots: Vec<&Path> = projects.iter().map(|p| p.root.as_path()).collect();
        for (done, project) in projects.iter().enumerate() {
            if ctx.should_stop() {
                break;
            }
            let others: Vec<&Path> = roots
                .iter()
                .copied()
                .filter(|r| *r != project.root && r.starts_with(&project.root))
                .collect();
            if let Some(item) = self.item(project, &others, ctx) {
                emit(item);
            }
            ctx.report(done as u64 + 1, Some(projects.len() as u64));
        }
        Ok(())
    }

    fn revalidate(&self, ctx: &AnalysisContext, item: &Item) -> Revalidation {
        let Some(root) = &item.project_hint else {
            return Revalidation::Gone;
        };
        let project = Self::projects(ctx)
            .into_iter()
            .find(|p| &p.root == root)
            .cloned()
            .unwrap_or_else(|| project_at(root));
        let others: Vec<&Path> = Self::projects(ctx)
            .into_iter()
            .map(|p| p.root.as_path())
            .filter(|r| *r != root && r.starts_with(root))
            .collect();
        let Some(mut fresh) = self.item(&project, &others, ctx) else {
            return Revalidation::Gone;
        };
        if let Some(signal) = in_use_signal(&fresh.parts, root, self.platform.as_ref(), &ctx.stop) {
            fresh.signals.push(signal);
        }
        Revalidation::StillValid(Box::new(fresh))
    }

    fn clean(&self, item: &Item, destination: Destination) -> Result<CleanOutcome, CollectorError> {
        if destination != Destination::Direct {
            return Err(CollectorError::Unsupported);
        }
        // Only `node_modules` folders inside the item's own project are ever removed (I4).
        let root = item.project_hint.as_deref().unwrap_or(Path::new(""));
        let outside = item.parts.iter().find(|folder| {
            folder.file_name() != Some(FOLDER.as_ref()) || !folder.starts_with(root)
        });
        if item.parts.is_empty() || root.as_os_str().is_empty() || outside.is_some() {
            return Err(CollectorError::Failed(Message::new("clean.outside_item")));
        }
        for folder in &item.parts {
            remove(folder).map_err(|e| {
                CollectorError::Failed(
                    Message::new("clean.remove_failed")
                        .with("path", folder.display())
                        .with("detail", e),
                )
            })?;
        }
        Ok(CleanOutcome::Cleaned {
            freed_bytes: item.freeable_size,
        })
    }
}

