#[test]
fn t04_01_ca6_a_file_in_use_blocks_the_item_on_revalidation() {
    let machine = FakeMachine::new().unwrap();
    let web = machine.project(&ProjectSpec::node("web")).unwrap();
    file(&web.join("node_modules/vite/dist/server.js"), 10);
    let items = analyze(&machine);
    let item = only(&items);

    let Revalidation::StillValid(free) = collector().revalidate(&ctx(&machine), item) else {
        panic!("still there");
    };
    assert!(free.signals.is_empty());

    let _dev_server = LockedFile::open(&web.join("node_modules/vite/dist/server.js")).unwrap();
    let Revalidation::StillValid(held) = collector().revalidate(&ctx(&machine), item) else {
        panic!("still there");
    };
    if cfg!(windows) {
        assert_eq!(assess(&held, None).risk, Risk::Blocked);
        let Signal::InUse(reason) = &held.signals[0] else {
            panic!("in use");
        };
        assert_eq!(reason.key, "signal.file_in_use");
        assert_eq!(
            reason.params["file"],
            Path::new("node_modules")
                .join("vite")
                .join("dist")
                .join("server.js")
                .display()
                .to_string()
        );
        assert!(!reason.params["process"].is_empty());
    }
}

#[test]
fn nested_repositories_are_their_own_items() {
    let machine = FakeMachine::new().unwrap();
    let mono = machine
        .project(&ProjectSpec::node("mono").with_git())
        .unwrap();
    file(&mono.join("node_modules/a/index.js"), 1);
    // A repository cloned inside another one is a project of its own.
    let nested = mono.join("vendor-repo");
    fs::create_dir_all(nested.join(".git")).unwrap();
    fs::write(nested.join("package.json"), "{}").unwrap();
    file(&nested.join("node_modules/b/index.js"), 2);

    let items = analyze(&machine);
    let names: Vec<&str> = items.iter().map(|i| i.name.as_str()).collect();
    assert_eq!(names.len(), 2, "{names:?}");
    let outer = items
        .iter()
        .find(|i| i.name == "mono · node_modules")
        .unwrap();
    assert_eq!(outer.parts, vec![mono.join("node_modules")]);
}

#[test]
fn projects_without_node_modules_give_nothing_and_progress_is_reported() {
    let machine = FakeMachine::new().unwrap();
    machine.project(&ProjectSpec::node("vazio")).unwrap();
    machine.project(&ProjectSpec::python("py")).unwrap();
    let progress = Arc::new(std::sync::Mutex::new(vec![]));
    let sink = Arc::clone(&progress);
    let discovery = discover(&[machine.roots()], &DiscoveryOptions::default());
    let ctx = AnalysisContext::new(
        vec![],
        Arc::new(crate::adapters::SystemClock),
        Arc::new(crate::collector::tests::NoCommands),
        StopSignal::new(None),
        Arc::new(move |p| sink.lock().unwrap().push((p.done, p.total))),
    )
    .with_discovery(Arc::new(discovery));
    let mut items = vec![];
    collector().analyze(&ctx, &mut |i| items.push(i)).unwrap();
    assert!(items.is_empty());
    assert_eq!(*progress.lock().unwrap(), vec![(1, Some(2)), (2, Some(2))]);
    assert_eq!(collector().detect(&ctx), Detection::Available);
}

