#[test]
fn revalidation_sees_a_removed_folder_as_gone() {
    let machine = FakeMachine::new().unwrap();
    let api = machine.project(&ProjectSpec::node("api")).unwrap();
    file(&api.join("node_modules/x/index.js"), 1);
    let items = analyze(&machine);
    fs::remove_dir_all(api.join("node_modules")).unwrap();
    assert_eq!(
        collector().revalidate(&ctx(&machine), &items[0]),
        Revalidation::Gone
    );
    // Even when the project is no longer under the roots.
    let mut moved = items[0].clone();
    moved.project_hint = None;
    assert_eq!(
        collector().revalidate(&ctx(&machine), &moved),
        Revalidation::Gone
    );
}

