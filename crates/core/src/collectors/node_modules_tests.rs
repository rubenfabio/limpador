use limpador_testkit::{FakeMachine, LockedFile, ProjectSpec, create_junction};

fn file(path: &Path, bytes: usize) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, vec![b'x'; bytes]).unwrap();
}

fn ctx(machine: &FakeMachine) -> AnalysisContext {
    let discovery = discover(&[machine.roots()], &DiscoveryOptions::default());
    context(StopSignal::new(None)).with_discovery(Arc::new(discovery))
}

fn collector() -> NodeModulesCollector {
    NodeModulesCollector::new(native_platform())
}

fn analyze(machine: &FakeMachine) -> Vec<Item> {
    let mut items = vec![];
    collector()
        .analyze(&ctx(machine), &mut |i| items.push(i))
        .unwrap();
    items
}

fn only(items: &[Item]) -> &Item {
    assert_eq!(items.len(), 1, "{items:#?}");
    &items[0]
}

#[test]
fn t04_01_ca1_a_monorepo_gives_one_item_with_every_folder() {
    let machine = FakeMachine::new().unwrap();
    let loja = machine
        .project(&ProjectSpec::node("loja").with_git())
        .unwrap();
    file(&loja.join("node_modules/react/index.js"), 100);
    file(&loja.join("packages/api/node_modules/express/index.js"), 20);
    file(&loja.join("packages/web/node_modules/vite/index.js"), 30);
    // Nested inside another node_modules: part of it, not a folder of its own.
    file(
        &loja.join("node_modules/react/node_modules/scheduler/index.js"),
        5,
    );

    let items = analyze(&machine);
    let item = only(&items);

    assert_eq!(
        item.parts,
        vec![
            loja.join("node_modules"),
            loja.join("packages").join("api").join("node_modules"),
            loja.join("packages").join("web").join("node_modules"),
        ]
    );
    assert_eq!(item.resource, Resource::Path(loja.join("node_modules")));
    assert_eq!((item.apparent_size, item.freeable_size), (155, 155));
    assert_eq!(item.name, "loja · node_modules");
    assert_eq!(item.project_hint.as_deref(), Some(loja.as_path()));
    assert_eq!(item.risk, Risk::Moderate);
    assert_eq!(
        item.reason,
        Message::new("reason.node_modules").with("count", 3)
    );
    assert_eq!(assess(item, None).destination, Some(Destination::Direct));
}

#[test]
fn t04_01_ca2_the_lock_file_says_how_to_reinstall() {
    for (lock, command) in [
        ("pnpm-lock.yaml", "pnpm install"),
        ("yarn.lock", "yarn install"),
        ("package-lock.json", "npm ci"),
        ("bun.lock", "bun install"),
        ("bun.lockb", "bun install"),
    ] {
        let machine = FakeMachine::new().unwrap();
        let api = machine.project(&ProjectSpec::node("api")).unwrap();
        fs::write(api.join(lock), "").unwrap();
        file(&api.join("node_modules/x/index.js"), 1);

        let items = analyze(&machine);
        let item = only(&items);
        assert_eq!(
            item.recreate,
            Some(Message::new("recreate.run_command").with("command", command)),
            "{lock}"
        );
        assert!(item.alerts.is_empty(), "{lock}");
    }
}

#[test]
fn t04_01_ca3_pnpm_hardlinks_to_the_store_are_not_freeable() {
    let machine = FakeMachine::new().unwrap();
    let api = machine.project(&ProjectSpec::node("api")).unwrap();
    fs::write(api.join("pnpm-lock.yaml"), "").unwrap();
    let store = machine.path("pnpm-store");
    let virtual_store = api.join("node_modules").join(".pnpm");
    for package in ["react", "vite", "typescript"] {
        file(&store.join(format!("{package}.js")), 10_000);
        fs::create_dir_all(virtual_store.join(package)).unwrap();
        fs::hard_link(
            store.join(format!("{package}.js")),
            virtual_store.join(package).join("index.js"),
        )
        .unwrap();
    }
    file(&api.join("node_modules/.modules.yaml"), 100);

    let items = analyze(&machine);
    let item = only(&items);
    assert_eq!(item.apparent_size, 30_100);
    assert_eq!(item.freeable_size, 100);
}

#[test]
fn t04_01_ca4_removing_keeps_the_target_of_a_junction_inside() {
    let machine = FakeMachine::new().unwrap();
    let web = machine.project(&ProjectSpec::node("web")).unwrap();
    let shared = machine.path("pacote-compartilhado");
    file(&shared.join("index.js"), 50);
    file(&web.join("node_modules/react/index.js"), 10);
    create_junction(&web.join("node_modules").join("compartilhado"), &shared).unwrap();

    let items = analyze(&machine);
    let item = only(&items);
    assert_eq!(item.apparent_size, 10, "the junction is not followed");

    let outcome = collector().clean(item, Destination::Direct).unwrap();
    assert_eq!(outcome, CleanOutcome::Cleaned { freed_bytes: 10 });
    assert!(!web.join("node_modules").exists());
    assert!(shared.join("index.js").exists());
    assert!(web.join("package.json").exists(), "only node_modules goes");
}

